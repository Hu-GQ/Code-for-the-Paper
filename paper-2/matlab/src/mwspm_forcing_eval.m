function f = mwspm_forcing_eval(F, t)
%MWSPM_FORCING_EVAL  Evaluate the forcing coefficients at continuous time t.
%
%   f = mwspm_forcing_eval(F, t) with f fields:
%       T, a, b, c, sigma_v, mu_v (unscaled), mu_eff, s, Nv, Lambda
%
%   t is elapsed days since the window start (0 .. n_days).  ZOH uses direct
%   indexing (t in [k, k+1) -> day k+1); 'linear' uses interp1.  Out-of-range
%   t is clamped to the window rather than extrapolated, so an accidental
%   over-run cannot silently invent forcing values.

if F.n == 0
    error('mwspm:forcing', 'empty forcing');
end

switch F.interp
    case 'zoh'
        idx = min(max(floor(t) + 1, 1), F.n);
        f = struct( ...
            'T',       F.T_daily(idx), ...
            'a',       F.a_daily(idx), ...
            'b',       F.b_daily(idx), ...
            'c',       F.c_daily(idx), ...
            'sigma_v', F.sigma_v_daily(idx), ...
            'mu_v',    F.mu_daily(idx), ...
            'mu_eff',  F.mu_eff_daily(idx), ...
            's',       F.s_daily(idx), ...
            'Nv',      F.Nv_daily(idx), ...
            'Lambda',  F.Lambda_daily(idx));
    case 'linear'
        tc = min(max(t, F.tGrid(1)), F.tGrid(end));
        f = struct( ...
            'T',       interp1(F.tGrid, F.T_daily, tc), ...
            'a',       interp1(F.tGrid, F.a_daily, tc), ...
            'b',       interp1(F.tGrid, F.b_daily, tc), ...
            'c',       interp1(F.tGrid, F.c_daily, tc), ...
            'sigma_v', interp1(F.tGrid, F.sigma_v_daily, tc), ...
            'mu_v',    interp1(F.tGrid, F.mu_daily, tc), ...
            'mu_eff',  interp1(F.tGrid, F.mu_eff_daily, tc), ...
            's',       interp1(F.tGrid, F.s_daily, tc), ...
            'Nv',      interp1(F.tGrid, F.Nv_daily, tc), ...
            'Lambda',  interp1(F.tGrid, F.Lambda_daily, tc));
    otherwise
        error('mwspm:forcing', 'unknown interpolation rule');
end
end
